"""Image and video generation for one task, with its video jobs persisted."""

from __future__ import annotations

import logging
from dataclasses import dataclass
from decimal import Decimal
from typing import Any
from uuid import UUID, uuid4

from agentarea_common.model_charges import (
    ModelCallRefusedError,
    ModelFunding,
    charge_model_call,
    release_model_hold,
)
from agentarea_common.money import Money

from agentarea_llm.application.model_call_pricing import (
    fund_model_call,
    image_estimate,
    video_estimate,
)
from agentarea_llm.application.model_service import ModelService
from agentarea_llm.domain.media import VideoJobStatus
from agentarea_llm.domain.model_kind import ModelKind
from agentarea_llm.infrastructure.model_clients import GeneratedMedia, ModelCallError
from agentarea_llm.infrastructure.video_generation_job_repository import (
    VideoGenerationJobRepository,
)

logger = logging.getLogger(__name__)


class MediaModelNotConfiguredError(ValueError):
    """The toolset was asked for a medium its settings name no model for."""


class VideoJobNotFoundError(LookupError):
    """No video job with this id was submitted by this task."""


@dataclass(frozen=True)
class BilledMedia:
    """Generated bytes and the line they cost.

    ``cost`` is the line's amount in ``currency``; ``billing`` is the rest of the line
    (``ModelCharge.as_billing()``: the hold to capture, who pays, whether the
    provider reported the cost at all).
    """

    content: bytes
    media_type: str
    cost: Money
    currency: str
    billing: dict[str, Any]
    cost_unknown: bool = False


@dataclass(frozen=True)
class SubmittedJob:
    """Our id for a submitted video generation; the provider's stays in the row."""

    job_id: str
    status: VideoJobStatus


@dataclass(frozen=True)
class VideoCheck:
    """Where a video job stands.

    ``video``, ``cost_usd`` (the provider's charge, None when it reported none),
    ``cost`` and ``billing`` (the line, as on ``BilledMedia``) are set when it
    finished and has not been saved yet; ``file_path`` when an earlier check already
    saved (and billed) it, with ``cost`` and ``billing`` again for a retry of the call
    that billed it.
    """

    job_id: str
    status: VideoJobStatus
    error: str | None = None
    video: GeneratedMedia | None = None
    cost_usd: Decimal | None = None
    cost: Money | None = None
    currency: str | None = None
    billing: dict[str, Any] | None = None
    file_path: str | None = None
    cost_unknown: bool = False


class MediaGenerationService:
    def __init__(
        self,
        *,
        models: ModelService,
        jobs: VideoGenerationJobRepository,
        workspace_id: str,
        task_id: str | None,
        image_model_id: str | None,
        video_model_id: str | None,
        call_ref: str,
    ) -> None:
        # The tool call this service acts for, the same on every retry of it; a
        # finished video is billed to exactly one call.
        self._call_ref = call_ref
        self._models = models
        self._jobs = jobs
        self._workspace_id = workspace_id
        self._task_id = task_id
        self._image_model_id = image_model_id
        self._video_model_id = video_model_id

    async def generate_image(self, prompt: str, *, size: str | None = None) -> BilledMedia:
        if not self._image_model_id:
            raise MediaModelNotConfiguredError("no image model is configured for agentarea/media")
        target = await self._models.describe(self._image_model_id, ModelKind.IMAGE)
        funding = await fund_model_call(
            target,
            workspace_id=self._workspace_id,
            estimate=image_estimate(target),
            idempotency_key=f"media:{self._call_ref}:{uuid4().hex}",
        )
        try:
            model = await self._models.image_model(target, funding)
            image = await model.generate(prompt, size=size)
        except BaseException:
            await release_model_hold(funding, "the image was not generated")
            raise
        charge = await charge_model_call(funding=funding, vendor_cost=image.cost_usd)
        return BilledMedia(
            content=image.content,
            media_type=image.media_type,
            cost=charge.amount,
            currency=charge.currency,
            billing=charge.as_billing(),
            cost_unknown=charge.cost_unknown,
        )

    async def submit_video(
        self,
        prompt: str,
        *,
        duration: int | None = None,
        resolution: str | None = None,
        aspect_ratio: str | None = None,
    ) -> SubmittedJob:
        if not self._video_model_id:
            raise MediaModelNotConfiguredError("no video model is configured for agentarea/media")
        target = await self._models.describe(self._video_model_id, ModelKind.VIDEO)
        try:
            funding = await fund_model_call(
                target,
                workspace_id=self._workspace_id,
                estimate=video_estimate(target, duration),
                idempotency_key=f"media:{self._call_ref}:{uuid4().hex}",
            )
        except ModelCallRefusedError as refused:
            if refused.code == "model_unpriced" and duration is None:
                raise ModelCallRefusedError(
                    "duration_required",
                    "a video on the platform's model is held by its length: pass duration",
                ) from refused
            raise
        try:
            model = await self._models.video_model(target, funding)
            submitted = await model.submit(
                prompt, duration=duration, resolution=resolution, aspect_ratio=aspect_ratio
            )
            job = await self._jobs.create(
                model_instance_id=UUID(target.instance_id),
                task_id=self._task_id,
                provider_job_id=submitted.provider_job_id,
                prompt=prompt,
                status=submitted.status,
                funding=funding.stored(),
            )
        except BaseException:
            await release_model_hold(funding, "the video was not submitted")
            raise
        return SubmittedJob(job_id=str(job.id), status=submitted.status)

    async def check_video(self, job_id: str) -> VideoCheck:
        try:
            job_uuid = UUID(job_id)
        except ValueError as error:
            raise VideoJobNotFoundError(f"video job {job_id!r} is not a job id") from error
        job = await self._jobs.get_for_task(job_uuid, self._task_id)
        if job is None:
            raise VideoJobNotFoundError(f"no video job {job_id} was submitted by this task")
        if job.file_path:
            # A retry of the call that billed it reports the line again; the
            # workflow keeps one result per call, so it is still counted once.
            billed_here = job.billed_call_ref == self._call_ref
            return VideoCheck(
                job_id=job_id,
                status=VideoJobStatus.COMPLETED,
                file_path=job.file_path,
                cost=job.billed_cost if billed_here else None,
                currency=(job.billing or {}).get("currency") if billed_here else None,
                billing=job.billing if billed_here else None,
                cost_unknown=bool(billed_here and (job.billing or {}).get("cost_unknown")),
            )
        stored = VideoJobStatus(job.status)
        if stored.is_failed:
            return VideoCheck(job_id=job_id, status=stored, error=job.error)

        if job.funding is None:
            raise ModelCallError(
                f"video job {job_id} was submitted before jobs kept their funding; "
                "it cannot be checked on this credential"
            )
        funding = ModelFunding.restore(job.funding)
        target = await self._models.describe(job.model_instance_id, ModelKind.VIDEO)
        model = await self._models.video_model(target, funding)
        status = await model.status(job.provider_job_id)
        if status.status.is_running:
            if status.status != stored:
                await self._jobs.update(job.id, status=status.status)
            return VideoCheck(job_id=job_id, status=status.status)
        if status.status.is_failed:
            error = status.error or f"the provider reports the job {status.status}"
            await self._jobs.update(job.id, status=status.status, error=error)
            await release_model_hold(funding, f"video job {job_id} failed")
            return VideoCheck(job_id=job_id, status=status.status, error=error)
        if status.status is not VideoJobStatus.COMPLETED:
            raise ModelCallError(f"video job {job_id} has unhandled status {status.status!r}")
        video = await model.content(job.provider_job_id)
        if status.cost_usd is None:
            logger.error(
                "Video job %s on model instance %s finished without a reported cost",
                job_id,
                job.model_instance_id,
            )
        charge = await charge_model_call(funding=funding, vendor_cost=status.cost_usd)
        return VideoCheck(
            job_id=job_id,
            status=VideoJobStatus.COMPLETED,
            video=video,
            cost_usd=status.cost_usd,
            cost=charge.amount,
            currency=charge.currency,
            billing=charge.as_billing(),
            cost_unknown=charge.cost_unknown,
        )

    async def record_video_saved(
        self,
        job_id: str,
        file_path: str,
        cost_usd: Decimal | None,
        cost: Money | None,
        billing: dict[str, Any] | None,
    ) -> bool:
        """Mark the job saved; True when this call is the one that bills it."""
        return await self._jobs.record_saved(
            UUID(job_id),
            file_path,
            cost_usd=cost_usd,
            billed_cost=cost,
            billing=billing,
            call_ref=self._call_ref,
        )
