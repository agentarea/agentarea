"""A generic webhook is signed from the moment it is created, and can be re-signed.

The secret is generated by the API and shown exactly once. What matters is that
the value handed to the person is the one the webhook endpoint then checks
requests against, so these tests verify signatures with the endpoint's own
verifier over the secret store the API wrote.
"""

