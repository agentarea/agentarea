package api

import (
	"context"

	"github.com/agentarea/agentarea/agentarea-platform/internal/kernel/money"
	"github.com/agentarea/agentarea/agentarea-platform/internal/kernel/scope"
)

// Video job states as the provider reports them (VideoJobStatus, OpenRouter /videos).
const (
	VideoPending    = "pending"
	VideoInProgress = "in_progress"
	VideoCompleted  = "completed"
	VideoFailed     = "failed"
	VideoCancelled  = "cancelled"
	VideoExpired    = "expired"
)

// VideoRunning: the job is still being generated.
func VideoRunning(status string) bool { return status == VideoPending || status == VideoInProgress }

// VideoEnded: the job failed, was cancelled or expired.
func VideoEnded(status string) bool {
	return status == VideoFailed || status == VideoCancelled || status == VideoExpired
}

// GeneratedMedia is generated bytes and what the provider charged for them in USD; CostUSD
// nil when neither the provider nor the spec says.
type GeneratedMedia struct {
	Content   []byte
	MediaType string
	CostUSD   *money.Decimal
}

// ImageCall is one image generation on a resolved image model (POST /images/generations).
type ImageCall struct {
	Model ResolvedModel
	// Funded: billing holds the call, so a platform credential may be used.
	Funded bool
	Prompt string
	Size   string
}

// VideoSubmission starts one video generation on a resolved video model (POST /videos).
type VideoSubmission struct {
	Model                   ResolvedModel
	Funded                  bool
	Prompt                  string
	Duration                *int
	Resolution, AspectRatio string
}

// SubmittedVideo is the provider's job id and the status it reported.
type SubmittedVideo struct {
	ProviderJobID string
	Status        string
}

// VideoJobCall reads one submitted generation.
type VideoJobCall struct {
	Model         ResolvedModel
	Funded        bool
	ProviderJobID string
}

// VideoProgress is where the provider says a job stands; CostUSD is what it reported.
type VideoProgress struct {
	Status  string
	CostUSD *money.Decimal
	Error   string
}

// Media calls image and video models (ImageModel, VideoModel). A failure the endpoint
// answered is a *ModelCallError that never repeats what it said.
type Media interface {
	GenerateImage(ctx context.Context, p Principal, c ImageCall) (GeneratedMedia, error)
	SubmitVideo(ctx context.Context, p Principal, v VideoSubmission) (SubmittedVideo, error)
	VideoStatus(ctx context.Context, p Principal, c VideoJobCall) (VideoProgress, error)
	VideoContent(ctx context.Context, p Principal, c VideoJobCall) (GeneratedMedia, error)
}

// NewVideoJob is a submitted generation of a task; Funding is the call's hold, kept
// across polls (ModelFunding.stored()).
type NewVideoJob struct {
	ModelInstanceID string
	TaskID          string
	ProviderJobID   string
	Prompt          string
	Status          string
	Funding         []byte
}

// VideoJob is a task's video job (VideoGenerationJob). FilePath is set once a call saved it;
// Billing and BilledCallRef are the line that call reported and the call.
type VideoJob struct {
	ID              string
	ModelInstanceID string
	ProviderJobID   string
	Status          string
	Error           string
	FilePath        string
	BilledCallRef   string
	Funding         []byte
	Billing         []byte
}

// SavedVideo is a finished video and the line that bills it.
type SavedVideo struct {
	FilePath   string
	CostUSD    *money.Decimal
	BilledCost *money.Decimal
	Billing    []byte
	CallRef    string
}

// VideoJobs keeps a workspace's video jobs (VideoGenerationJobRepository).
type VideoJobs interface {
	CreateVideoJob(ctx context.Context, ws scope.Workspace, userID string, j NewVideoJob) (string, error)
	// VideoJobOfTask is the job only when the task submitted it; found false otherwise.
	VideoJobOfTask(ctx context.Context, ws scope.Workspace, jobID, taskID string) (VideoJob, bool, error)
	SetVideoJobStatus(ctx context.Context, ws scope.Workspace, jobID, status, errText string) error
	// RecordVideoSaved marks the job saved; true when callRef is the call that bills it,
	// the first to record it or a retry of that call.
	RecordVideoSaved(ctx context.Context, ws scope.Workspace, jobID string, v SavedVideo) (bool, error)
}
